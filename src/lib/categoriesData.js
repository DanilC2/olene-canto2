export function getCategoryById(idOrSlug) {
  if (!idOrSlug) return null;
  const normalized = idOrSlug.toString().toLowerCase().trim();
  const canonicalId = SLUG_ALIASES[normalized] || normalized;
  return CATEGORIES_SHOWCASE.find((cat) => cat.id === canonicalId) || null;
}

export function getProductsByCategory(categoryIdOrSlug) {
  if (!categoryIdOrSlug) return [];
  const normalized = categoryIdOrSlug.toString().toLowerCase().trim();
  const canonicalId = SLUG_ALIASES[normalized] || normalized;
  return CATEGORY_PRODUCTS[canonicalId] || [];
}

export function getAllProducts() {
  const seen = new Set();
  const list = [];
  for (const items of Object.values(CATEGORY_PRODUCTS)) {
    if (!Array.isArray(items)) continue;
    for (const item of items) {
      if (item && item.id && !seen.has(item.id)) {
        seen.add(item.id);
        list.push(item);
      }
    }
  }
  return list;
}